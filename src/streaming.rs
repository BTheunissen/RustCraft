//! Bounded, nearest-first terrain generation on a background worker.

use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::mpsc::{self, Receiver, SyncSender, TryRecvError, TrySendError};
use std::thread::{self, JoinHandle};

use crate::mesh::ChunkMesh;
use crate::world::{Chunk, ChunkCoord, Terrain, WorldEdits};

mod residency;
mod worker;

use residency::Residency;
use worker::{WorkRequest, WorkerResult, run_worker};

const MAX_IN_FLIGHT: usize = 8;

/// Mesh data ready to be uploaded by the render thread.
pub struct PreparedChunk {
    /// World-space chunk column coordinate.
    pub coord: ChunkCoord,
    /// Edited CPU voxels for simulation and presentation, generated by the same worker.
    pub chunk: Chunk,
    /// Exposed opaque and water surfaces.
    pub mesh: ChunkMesh,
    /// Immutable session snapshot used to generate both the chunk and its halo.
    pub edit_revision: u64,
    /// Unique request identity; replacements never reuse an outstanding token.
    pub request_token: u64,
}

/// Generates only a bounded queue of chunks while the application keeps rendering.
pub struct ChunkStreamer {
    residency: Residency,
    edits: Arc<WorldEdits>,
    requests: Option<SyncSender<WorkRequest>>,
    results: Receiver<WorkerResult>,
    stop: Arc<AtomicBool>,
    worker: Option<JoinHandle<()>>,
    disconnected: bool,
}

impl ChunkStreamer {
    /// Starts one CPU worker. `radius` is clamped to 1–16 chunk columns.
    pub fn new(terrain: Terrain, center: ChunkCoord, radius: i32) -> std::io::Result<Self> {
        let (requests, work) = mpsc::sync_channel(MAX_IN_FLIGHT);
        let (finished, results) = mpsc::sync_channel(MAX_IN_FLIGHT);
        let stop = Arc::new(AtomicBool::new(false));
        let worker_stop = Arc::clone(&stop);
        let worker = thread::Builder::new()
            .name("rustcraft-terrain".into())
            .spawn(move || run_worker(terrain, work, finished, &worker_stop))?;
        Ok(Self {
            residency: Residency::new(center, radius.clamp(1, 16)),
            edits: Arc::new(WorldEdits::default()),
            requests: Some(requests),
            results,
            stop,
            worker: Some(worker),
            disconnected: false,
        })
    }

    /// Synchronizes session edits before polling or recentering each frame.
    /// Unchanged revisions are O(1). Changed chunks invalidate their full 3×3
    /// halo, including diagonal water corners and vertical daylight columns.
    pub fn sync_edits(&mut self, edits: &WorldEdits) {
        if self.edits.revision() == edits.revision() {
            return;
        }
        let affected = edits.affected_chunks(&self.edits);
        self.residency.invalidate(&affected);
        self.edits = Arc::new(edits.clone());
        self.request_missing();
    }

    /// Reprioritizes work and returns resident chunks that should be removed from the GPU.
    pub fn update_center(&mut self, center: ChunkCoord) -> Vec<ChunkCoord> {
        let evicted = self.residency.recenter(center);
        self.request_missing();
        evicted
    }

    fn request_missing(&mut self) {
        let Some(requests) = &self.requests else {
            return;
        };
        for coord in self.residency.next_requests() {
            let stamp = self
                .residency
                .request_stamp(self.edits.halo_revision(coord));
            let request = WorkRequest {
                coord,
                stamp: stamp.clone(),
                edits: Arc::clone(&self.edits),
            };
            match requests.try_send(request) {
                Ok(()) => {
                    self.residency.in_flight.insert(coord, stamp);
                }
                Err(TrySendError::Full(_)) => break,
                Err(TrySendError::Disconnected(_)) => {
                    self.disconnected = true;
                    break;
                }
            }
        }
    }

    /// Drains a limited number of meshes, discarding obsolete results after rapid travel.
    pub fn poll_ready(&mut self, budget: usize) -> Vec<PreparedChunk> {
        let mut ready = Vec::new();
        for _ in 0..budget {
            match self.results.try_recv() {
                Ok(result) => {
                    let complete = result.prepared.is_some();
                    let current = self.residency.accept(
                        result.coord,
                        result.token,
                        self.edits.halo_revision(result.coord),
                        complete,
                    );
                    if current && let Some(chunk) = result.prepared {
                        ready.push(chunk);
                    }
                }
                Err(TryRecvError::Empty) => break,
                Err(TryRecvError::Disconnected) => {
                    self.disconnected = true;
                    break;
                }
            }
        }
        self.request_missing();
        ready
    }

    /// Number of current-area chunks uploaded or awaiting upload by the caller.
    pub fn loaded_count(&self) -> usize {
        self.residency.resident.len()
    }

    /// Desired chunks still missing or waiting for an edited mesh replacement.
    pub fn pending_count(&self) -> usize {
        self.residency.pending_count()
    }

    /// Detects a failed worker instead of silently leaving an empty world.
    pub fn worker_failed(&self) -> bool {
        self.disconnected
    }
}

impl Drop for ChunkStreamer {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Relaxed);
        self.requests.take();
        // Drain while joining: a worker must never be stranded on a full result channel.
        if let Some(worker) = self.worker.take() {
            while !worker.is_finished() {
                let _ = self
                    .results
                    .recv_timeout(std::time::Duration::from_millis(20));
            }
            let _ = worker.join();
        }
    }
}

